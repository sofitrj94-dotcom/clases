//push 

let lista=[]
lista.push("a")
console.log(lista)
lista.push("b")
console.log(lista)

//push es para agregar al final de un arreglo


//unshift

lista.unshift("c")
console.log(lista)

//unshift es para agregar al inicio de un arreglo


//pop
lista.pop()
console.log(lista)

//pop es para eliminar elementos al final 

//shift 
lista.shift()
console.log(lista)

//shift es para eliminar elementos al inicio